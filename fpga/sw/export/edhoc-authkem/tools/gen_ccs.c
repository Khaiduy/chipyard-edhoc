/* Build-time generator for AuthKEM CCS credentials.
 *
 * A CCS credential is a fixed 14-byte CBOR prefix followed by the raw ML-KEM
 * public key (see include/authkem_cred.h). The firmware used to build both
 * credentials into .bss at startup from constant inputs -- 1,628 B of a 64 kB
 * scratchpad holding a value known at build time, on a target whose measured
 * stack peak was within 1.1 kB of the 25% margin it needs.
 *
 * Emitting them as .rodata removes that RAM entirely. The raw public key is
 * not stored twice: it lives inside the credential and the firmware indexes
 * past the prefix to reach it.
 *
 * Output is a generated header; the credentials are validated here, and the
 * header carries _Static_asserts so a mismatch fails the firmware build too.
 */
#include <stdio.h>
#include <stdint.h>
#include <string.h>

#include "authkem_cred.h"
#include "authkem_test_keys.h"

static int emit(FILE *f, const char *name, const uint8_t *pk, uint32_t pk_len)
{
	uint8_t ccs[AUTHKEM_CRED_SIZE(sizeof(INIT_PK))];
	uint32_t len = authkem_build_ccs(ccs, sizeof ccs, pk, pk_len);

	if (len != AUTHKEM_CRED_SIZE(pk_len)) {
		fprintf(stderr, "gen_ccs: %s: builder returned %u, expected %u\n",
			name, len, (unsigned)AUTHKEM_CRED_SIZE(pk_len));
		return -1;
	}
	/* The firmware reads the public key as ccs + AUTHKEM_CRED_OVERHEAD.
	 * Verify that actually holds before baking it in. */
	if (memcmp(ccs + AUTHKEM_CRED_OVERHEAD, pk, pk_len) != 0) {
		fprintf(stderr, "gen_ccs: %s: key not at offset %u\n", name,
			AUTHKEM_CRED_OVERHEAD);
		return -1;
	}

	fprintf(f, "static const uint8_t %s[%u] = {", name, len);
	for (uint32_t i = 0; i < len; i++)
		fprintf(f, "%s0x%02x,", (i % 12) ? " " : "\n\t", ccs[i]);
	fprintf(f, "\n};\n");
	fprintf(f, "#define %s_LEN %uu\n\n", name, len);
	return 0;
}

int main(int argc, char **argv)
{
	if (argc != 2) {
		fprintf(stderr, "usage: %s <out.h>\n", argv[0]);
		return 2;
	}
	FILE *f = fopen(argv[1], "w");
	if (!f) {
		perror("gen_ccs: open");
		return 1;
	}

	fprintf(f,
		"/* GENERATED by tools/gen_ccs.c -- do not edit.\n"
		" *\n"
		" * AuthKEM CCS credentials in .rodata. Built from the ML-KEM-512\n"
		" * key pairs in src/authkem_test_keys.h, which are DEMO keys:\n"
		" * this header must never be part of a production image. The\n"
		" * production profile refuses to compile it (see mk/config.mk).\n"
		" */\n"
		"#ifndef AUTHKEM_CREDS_GENERATED_H\n"
		"#define AUTHKEM_CREDS_GENERATED_H\n\n"
		"#include <stdint.h>\n"
		"#include \"authkem_cred.h\"\n\n");

	if (emit(f, "CRED_I_CCS", INIT_PK, sizeof(INIT_PK)) ||
	    emit(f, "CRED_R_CCS", RESP_PK, sizeof(RESP_PK))) {
		fclose(f);
		return 1;
	}

	fprintf(f,
		"/* The firmware reaches the raw public key by indexing past the\n"
		" * CBOR prefix rather than keeping a second copy of it. */\n"
		"#define CRED_I_PK (CRED_I_CCS + AUTHKEM_CRED_OVERHEAD)\n"
		"#define CRED_R_PK (CRED_R_CCS + AUTHKEM_CRED_OVERHEAD)\n\n"
		"_Static_assert(CRED_I_CCS_LEN == AUTHKEM_CRED_SIZE(%u),\n"
		"\t       \"CRED_I_CCS size disagrees with AUTHKEM_CRED_SIZE\");\n"
		"_Static_assert(CRED_R_CCS_LEN == AUTHKEM_CRED_SIZE(%u),\n"
		"\t       \"CRED_R_CCS size disagrees with AUTHKEM_CRED_SIZE\");\n\n"
		"#endif /* AUTHKEM_CREDS_GENERATED_H */\n",
		(unsigned)sizeof(INIT_PK), (unsigned)sizeof(RESP_PK));

	fclose(f);
	return 0;
}
