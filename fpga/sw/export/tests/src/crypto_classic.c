/*
 * crypto_classic.c — known-answer tests for the classical primitives EDHOC
 * (RFC 9528) uses, run on the target against the implementations the EDHOC
 * firmware links: ../common/crypto (SHA-2, HMAC/HKDF, AES-CCM/GCM) and
 * curve25519-donna (X25519).
 *
 * Covers requirement B6 for the non-PQ algorithms. Every expected value below
 * is a published vector, so this is a real KAT, not a self-consistency check:
 *
 *   SHA-256      FIPS 180-4 "abc"
 *   SHA-384      FIPS 180-4 "abc"
 *   HMAC-SHA-256 RFC 4231 test case 1
 *   HKDF-SHA-256 RFC 5869 test case 1
 *   AES-128-CCM  RFC 3610 packet vector #1
 *   AES-128-GCM  NIST GCM spec, test case 2
 *   AES-256-GCM  NIST GCM spec, test case 14 (pqsuites TBD2/TBD3, suite 24)
 *   X25519       RFC 7748 section 6.1 (Alice/Bob shared secret)
 *
 * The AEAD tests also decrypt the expected ciphertext and check the tag
 * verifies. A mismatch prints both got and want so the failure is
 * diagnosable from the console alone.
 */
