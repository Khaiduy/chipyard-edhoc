static int test_x25519(void)
{
	/* RFC 7748 section 6.1: Alice and Bob must agree on K */
	static const uint8_t a_priv[32] = {
		0x77,0x07,0x6D,0x0A,0x73,0x18,0xA5,0x7D,0x3C,0x16,0xC1,0x72,0x51,0xB2,0x66,0x45,
		0xDF,0x4C,0x2F,0x87,0xEB,0xC0,0x99,0x2A,0xB1,0x77,0xFB,0xA5,0x1D,0xB9,0x2C,0x2A };
	static const uint8_t b_pub[32] = {
		0xDE,0x9E,0xDB,0x7D,0x7B,0x7D,0xC1,0xB4,0xD3,0x5B,0x61,0xC2,0xEC,0xE4,0x35,0x37,
		0x3F,0x83,0x43,0xC8,0x5B,0x78,0x67,0x4D,0xAD,0xFC,0x7E,0x14,0x6F,0x88,0x2B,0x4F };
	static const uint8_t want[32] = {
		0x4A,0x5D,0x9D,0x5B,0xA4,0xCE,0x2D,0xE1,0x72,0x8E,0x3B,0xF4,0x80,0x35,0x0F,0x25,
		0xE0,0x7E,0x21,0xC9,0x47,0xD1,0x9E,0x33,0x76,0xF0,0x9B,0x3C,0x1E,0x16,0x17,0x42 };
	uint8_t out[32];
	uint64_t t0 = read_cycles();

	curve25519_donna(out, a_priv, b_pub);
	kprintf("  X25519 shared : %u cycles\r\n",
		(unsigned)(read_cycles() - t0));
	return report("X25519        ", out, want, 32);
}

int main(void)
{
	int fails = 0;

	test_console_init();

	kprintf("\r\n=== Classical crypto KAT (common/crypto, donna) ===\r\n");
	kprintf("  vectors: FIPS 180-4, RFC 4231, RFC 5869, RFC 3610, NIST GCM, RFC 7748\r\n");

	fails += test_sha256();
	fails += test_sha384();
	fails += test_hmac_sha256();
	fails += test_hkdf();
	fails += test_aes_ccm();
	fails += test_aes128_gcm();
	fails += test_aes256_gcm();
	fails += test_x25519();

	kprintf("\r\nCRYPTO TEST: %s (%d failures)\r\n",
		fails ? "FAIL" : "PASS", fails);
	while (1)
		;
	return 0;
}
