static int test_hmac_sha256(void)
{
	/* RFC 4231 test case 1: key = 20 x 0x0b, data = "Hi There" */
	static const uint8_t key[20] = {
		0x0b,0x0b,0x0b,0x0b,0x0b,0x0b,0x0b,0x0b,0x0b,0x0b,
		0x0b,0x0b,0x0b,0x0b,0x0b,0x0b,0x0b,0x0b,0x0b,0x0b };
	static const uint8_t want[32] = {
		0xB0,0x34,0x4C,0x61,0xD8,0xDB,0x38,0x53,0x5C,0xA8,0xAF,0xCE,0xAF,0x0B,0xF1,0x2B,
		0x88,0x1D,0xC2,0x00,0xC9,0x83,0x3D,0xA7,0x26,0xE9,0x37,0x6C,0x2E,0x32,0xCF,0xF7 };
	uint8_t out[32];
	struct hmac_ctx m;

	hmac_init(&m, &hash_sha256, key, sizeof(key));
	hmac_update(&m, (const uint8_t *)"Hi There", 8);
	hmac_final(&m, out);
	return report("HMAC-SHA-256  ", out, want, 32);
}

static int test_hkdf(void)
{
	/* RFC 5869 test case 1 (SHA-256), first 42 bytes of OKM */
	static const uint8_t ikm[22] = {
		0x0b,0x0b,0x0b,0x0b,0x0b,0x0b,0x0b,0x0b,0x0b,0x0b,0x0b,
		0x0b,0x0b,0x0b,0x0b,0x0b,0x0b,0x0b,0x0b,0x0b,0x0b,0x0b };
	static const uint8_t salt[13] = {
		0x00,0x01,0x02,0x03,0x04,0x05,0x06,0x07,0x08,0x09,0x0a,0x0b,0x0c };
	static const uint8_t info[10] = {
		0xf0,0xf1,0xf2,0xf3,0xf4,0xf5,0xf6,0xf7,0xf8,0xf9 };
	static const uint8_t want[42] = {
		0x3C,0xB2,0x5F,0x25,0xFA,0xAC,0xD5,0x7A,0x90,0x43,0x4F,0x64,0xD0,0x36,0x2F,0x2A,
		0x2D,0x2D,0x0A,0x90,0xCF,0x1A,0x5A,0x4C,0x5D,0xB0,0x2D,0x56,0xEC,0xC4,0xC5,0xBF,
		0x34,0x00,0x72,0x08,0xD5,0xB8,0x87,0x18,0x58,0x65 };
	uint8_t prk[32], out[42];

	hkdf_extract_h(&hash_sha256, salt, sizeof(salt), ikm, sizeof(ikm), prk);
	if (hkdf_expand_h(&hash_sha256, prk, sizeof(prk), info, sizeof(info),
			  out, sizeof(out)) != 0) {
		kprintf("  %s: FAIL (call error)\r\n", "HKDF-SHA-256  ");
		return 1;
	}
	return report("HKDF-SHA-256  ", out, want, sizeof(want));
}

static int test_aes_ccm(void)
{
	/* RFC 3610 packet vector #1: 8-byte tag, 13-byte nonce */
	static const uint8_t key[16] = {
		0xC0,0xC1,0xC2,0xC3,0xC4,0xC5,0xC6,0xC7,0xC8,0xC9,0xCA,0xCB,0xCC,0xCD,0xCE,0xCF };
	static const uint8_t nonce[13] = {
		0x00,0x00,0x00,0x03,0x02,0x01,0x00,0xA0,0xA1,0xA2,0xA3,0xA4,0xA5 };
	static const uint8_t aad[8] = { 0x00,0x01,0x02,0x03,0x04,0x05,0x06,0x07 };
	static const uint8_t pt[23] = {
		0x08,0x09,0x0A,0x0B,0x0C,0x0D,0x0E,0x0F,0x10,0x11,0x12,0x13,
		0x14,0x15,0x16,0x17,0x18,0x19,0x1A,0x1B,0x1C,0x1D,0x1E };
	static const uint8_t want_ct[23] = {
		0x58,0x8C,0x97,0x9A,0x61,0xC6,0x63,0xD2,0xF0,0x66,0xD0,0xC2,
		0xC0,0xF9,0x89,0x80,0x6D,0x5F,0x6B,0x61,0xDA,0xC3,0x84 };
	static const uint8_t want_tag[8] = {
		0x17,0xE8,0xD1,0x2C,0xFD,0xF9,0x26,0xE0 };
	uint8_t ct[23], tag[8], dec[23];
	int fails = 0;

	aes_ccm_encrypt(key, nonce, aad, sizeof(aad), pt, sizeof(pt), ct, tag,
			sizeof(tag));
	fails += report("AES-128-CCM   ", ct, want_ct, sizeof(ct));
	fails += report("  CCM tag     ", tag, want_tag, sizeof(tag));
	if (aes_ccm_decrypt(key, nonce, aad, sizeof(aad), want_ct, sizeof(want_ct),
			    want_tag, sizeof(want_tag), dec) != 0) {
		kprintf("  %s: FAIL (tag rejected)\r\n", "  CCM decrypt ");
		return fails + 1;
	}
	return fails + report("  CCM decrypt ", dec, pt, sizeof(pt));
}

/* NIST GCM spec: all-zero key and IV, 16 zero bytes of plaintext, no AAD.
 * Test case 2 (key_len 16) and test case 14 (key_len 32). */
static int test_aes_gcm(const char *name, uint32_t key_len,
			const uint8_t want_ct[16], const uint8_t want_tag[16])
{
	static const uint8_t key[32] = { 0 };
	static const uint8_t iv[12] = { 0 };
	static const uint8_t pt[16] = { 0 };
	uint8_t ct[16], tag[16], dec[16];
	int fails = 0;

	aes_gcm_encrypt(key, key_len, iv, NULL, 0, pt, sizeof(pt), ct, tag);
	fails += report(name, ct, want_ct, sizeof(ct));
	fails += report("  GCM tag     ", tag, want_tag, sizeof(tag));
	if (aes_gcm_decrypt(key, key_len, iv, NULL, 0, want_ct, sizeof(ct),
			    want_tag, dec) != 0) {
		kprintf("  %s: FAIL (tag rejected)\r\n", "  GCM decrypt ");
		return fails + 1;
	}
	return fails + report("  GCM decrypt ", dec, pt, sizeof(pt));
}

