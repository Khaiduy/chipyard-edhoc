static uint32_t subword(uint32_t a)
{
	return ((uint32_t)sbox[a >> 24] << 24) | ((uint32_t)sbox[(a >> 16) & 0xff] << 16) |
	       ((uint32_t)sbox[(a >> 8) & 0xff] << 8) | sbox[a & 0xff];
}

static uint8_t xtime(uint8_t a)
{
	return (uint8_t)((a << 1) ^ ((a >> 7) * 0x1b));
}

void aes_setkey(struct aes_key *ak, const uint8_t *k, uint32_t key_len)
{
	uint32_t nk = key_len / 4, *w = ak->w;
	uint8_t rcon = 0x01;
	uint32_t i, t;

	ak->nr = nk + 6;
	for (i = 0; i < nk; i++)
		w[i] = ((uint32_t)k[4 * i] << 24) | ((uint32_t)k[4 * i + 1] << 16) |
		       ((uint32_t)k[4 * i + 2] << 8) | k[4 * i + 3];
	for (; i < Nb * (ak->nr + 1); i++) {
		t = w[i - 1];
		if (i % nk == 0) {
			t = subword((t << 8) | (t >> 24)) ^ ((uint32_t)rcon << 24);
			rcon = xtime(rcon);
		} else if (nk > 6 && i % nk == 4) {
			t = subword(t);
		}
		w[i] = w[i - nk] ^ t;
	}
}

/* One 1 KiB round table, Te0[x] = S[x] * {02, 01, 01, 03} as a big-endian
 * column; the other three are its byte rotations. Built from sbox on first
 * use. A full round is then 16 lookups and XORs on 32-bit columns instead of
 * byte loops: about 6x faster on this core, which matters for the bulk
 * channel (15 blocks per 192-byte record). Same table-lookup class as the
 * S-box before: not hardened against cache timing. */
static uint32_t te0[256];

static void te0_init(void)
{
	for (int x = 0; x < 256; x++) {
		uint8_t a = sbox[x], a2 = xtime(a);
		te0[x] = (uint32_t)a2 << 24 | (uint32_t)a << 16 | (uint32_t)a << 8 |
			 (uint8_t)(a2 ^ a);
	}
}

static uint32_t ror(uint32_t x, int n)
{
	return (x >> n) | (x << (32 - n));
}

static uint32_t be32(const uint8_t *p)
{
	return (uint32_t)p[0] << 24 | (uint32_t)p[1] << 16 | (uint32_t)p[2] << 8 | p[3];
}

static void put_be32(uint8_t *p, uint32_t v)
{
	p[0] = (uint8_t)(v >> 24);
	p[1] = (uint8_t)(v >> 16);
	p[2] = (uint8_t)(v >> 8);
	p[3] = (uint8_t)v;
}

#define TE(a, b, c, d) (te0[(a) >> 24] ^ ror(te0[((b) >> 16) & 0xff], 8) ^ \
			ror(te0[((c) >> 8) & 0xff], 16) ^ ror(te0[(d) & 0xff], 24))
#define SB(a, b, c, d) ((uint32_t)sbox[(a) >> 24] << 24 | \
			(uint32_t)sbox[((b) >> 16) & 0xff] << 16 | \
			(uint32_t)sbox[((c) >> 8) & 0xff] << 8 | sbox[(d) & 0xff])

void aes_encrypt_block(const struct aes_key *k, const uint8_t in[16],
		       uint8_t out[16])
{
	const uint32_t *w = k->w;
	uint32_t s0, s1, s2, s3, t0, t1, t2, t3;

	if (!te0[0])                 /* Te0[0] = c66363a5, never 0 once built */
		te0_init();
	s0 = be32(in) ^ w[0];
	s1 = be32(in + 4) ^ w[1];
	s2 = be32(in + 8) ^ w[2];
	s3 = be32(in + 12) ^ w[3];
	for (uint32_t r = 1; r < k->nr; r++) {
		w += 4;
		t0 = TE(s0, s1, s2, s3) ^ w[0];
		t1 = TE(s1, s2, s3, s0) ^ w[1];
		t2 = TE(s2, s3, s0, s1) ^ w[2];
		t3 = TE(s3, s0, s1, s2) ^ w[3];
		s0 = t0; s1 = t1; s2 = t2; s3 = t3;
	}
	w += 4;
	put_be32(out, SB(s0, s1, s2, s3) ^ w[0]);
	put_be32(out + 4, SB(s1, s2, s3, s0) ^ w[1]);
	put_be32(out + 8, SB(s2, s3, s0, s1) ^ w[2]);
	put_be32(out + 12, SB(s3, s0, s1, s2) ^ w[3]);
}
